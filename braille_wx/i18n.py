def t(key: str, **kwargs) -> str:
    """أعد النص المترجم للمفتاح، مع الرجوع للإنجليزية ثم العربية."""
    lang = _base.get_lang()
    order = (
        EXTRA.get(lang, {}),
        _base.STRINGS.get(lang, {}),
        EXTRA["en"],
        _base.STRINGS["en"],
        EXTRA["ar"],
        _base.STRINGS["ar"],
    )
    text = None
    for table in order:
        if key in table:
            text = table[key]
            break
    if text is None:
        text = key
    if kwargs:
        try:
            return text.format(**kwargs)
        except Exception:
            return text
    return text


