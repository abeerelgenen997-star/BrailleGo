def set_lang(lang: str) -> None:
    global _current_lang
    if lang in STRINGS:
        _current_lang = lang


def get_lang() -> str:
    return _current_lang


def t(key: str, **kwargs) -> str:
    # الترتيب: اللغة الحالية، ثم الإنجليزية، ثم العربية، وأخيرًا المفتاح نفسه.
    lang = _current_lang
    text = None
    for candidate in (lang, "en", "ar"):
        table = STRINGS.get(candidate, {})
        if key in table:
            text = table[key]
            break
    if text is None:
        text = key
    if kwargs:
        try:
            return text.format(**kwargs)
        except Exception:
            return text
    return text
